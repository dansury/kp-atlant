<?php
/**
 * Позиции, вытащенные из текста письма без модели (модуль 026).
 *
 * Письмо: «Просим вас рассмотреть возможность поставки в адрес ООО
 * „Газпромнефть-Терминал“ и направить КП на поставку следующей продукции:
 * Тактические наушники AMP в количестве 5 шт. Или аналог. Доставку просим
 * включить в стоимость товара.» — и ни одной позиции в карточке. Разбор
 * позиций целиком лежал на нейросети: «в количестве 5 шт» она читала как
 * оборот речи, а не как строку заказа, и запрос приходил менеджеру пустым.
 *
 * Здесь тот же текст разбирается правилами: количество — это число и единица
 * измерения рядом с ним, название — то, что стоит перед ними. Это ЗАПАСНОЙ
 * путь: он включается, только когда модель не нашла ничего. Так письмо не
 * теряет позиции ни от кривого ответа модели, ни от отсутствия ключа, ни от
 * упавшей сети — а ошибка в количестве здесь невозможна по построению: число
 * берётся из письма, а не сочиняется.
 *
 * Чего здесь нарочно нет — догадок. Строка без числа позицией не становится:
 * «Доставку просим включить в стоимость товара» — это просьба, а не товар.
 */
final class ItemLines {

    /** Единицы измерения, по которым узнаётся количество. */
    private const UNITS = 'шт|штук|штуки|штука|компл|комплект|комплекта|комплектов|пар|пара|пары'
                        . '|ед|единиц|уп|упак|упаковк[аи]|набор|наборов|кг|м|мм|см|пог\.?\s*м';

    /**
     * Слова, после которых число — не количество товара.
     *
     * «в течение 14 дней», «предоплата 100%», «срок 30 календарных дней» —
     * числа в письме есть всегда, и половина из них к заказу не относится.
     */
    private const NOT_A_POSITION = [
        'срок', 'предоплат', 'оплат', 'отсрочк', 'гарант', 'доставк', 'самовывоз',
        'скидк', 'ндс', 'итого', 'всего на сумму', 'реквизит', 'телефон', 'инн',
        'с уважением', 'здравствуйте', 'добрый день', 'добрый вечер', 'доброе утро',
    ];

    /** Метка вместо точки сокращения на время разрезки: «5 шт.» — не конец фразы. */
    private const DOT = "\x01";

    /** Мусор в начале строки списка: «1.», «№3», «—», «•». */
    private const LEAD_JUNK = '/^(?:[№n]\s*\d+|\d{1,3}\s*[.)]|[-–—•*·>]+)\s*/ui';

    /**
     * Позиции из текста письма.
     *
     * @return array<int,array{name:string,qty:float,raw_text:string}>
     */
    public static function extract(string $text): array {
        $out = [];
        foreach (self::segments($text) as $segment) {
            $item = self::parseSegment($segment);
            if (!$item) continue;
            // Одна и та же позиция, названная дважды, — это одна позиция
            $key = mb_strtolower($item['name']);
            if (isset($out[$key])) continue;
            $out[$key] = $item;
        }
        return array_values($out);
    }

    /**
     * Куски, в каждом из которых может стоять одна позиция: строки письма,
     * разрезанные ещё и по «;» и по концу предложения.
     *
     * Точка после «шт.» концом предложения не считается — иначе «5 шт. Или
     * аналог» разваливалось бы ровно посередине количества.
     */
    private static function segments(string $text): array {
        $text = str_replace(["\xC2\xA0", "\r"], [' ', "\n"], $text);
        $out = [];
        foreach (preg_split('/\n+/u', $text) ?: [] as $line) {
            $line = trim((string)preg_replace('/[ \t]+/u', ' ', $line));
            if ($line === '') continue;
            // «шт.» и «компл.» — не конец предложения, а сокращение
            $guarded = (string)preg_replace('/\b(' . self::UNITS . ')\./ui', '${1}' . self::DOT, $line);
            foreach (preg_split('/[;]|(?<=[.!?])\s+/u', $guarded) ?: [] as $chunk) {
                $chunk = trim(str_replace(self::DOT, '.', $chunk));
                if ($chunk !== '') $out[] = $chunk;
            }
        }
        return $out;
    }

    /** Одна позиция из куска текста, или null — позиции здесь нет. */
    private static function parseSegment(string $segment): ?array {
        $low = mb_strtolower($segment);
        foreach (self::NOT_A_POSITION as $stop) {
            if (mb_strpos($low, $stop) !== false) return null;
        }

        // Количество: «в количестве 5 шт», «— 10 шт.», «, 3 компл», «5 шт»
        $re = '/^(?<name>.{3,200}?)\s*[-–—:,]?\s*(?:в\s+количестве\s+|кол-?во[:\s]+|количество[:\s]+)?'
            . '(?<qty>\d+(?:[.,]\d+)?)\s*(?:' . self::UNITS . ')\b\.?/ui';
        if (!preg_match($re, $segment, $m)) return null;

        $name = self::cleanName((string)$m['name']);
        if ($name === '') return null;

        $qty = (float)str_replace(',', '.', (string)$m['qty']);
        if ($qty <= 0) return null;

        return ['name' => $name, 'qty' => $qty, 'raw_text' => $segment];
    }

    /** Название без нумерации списка, без хвостовых знаков и без «или аналог». */
    private static function cleanName(string $name): string {
        $name = (string)preg_replace(self::LEAD_JUNK, '', trim($name));
        $name = (string)preg_replace('/\s*(?:или\s+аналог\w*|аналог\w*)\s*$/ui', '', $name);
        $name = trim($name, " \t.,;:-–—");
        // В названии должны быть буквы: «5 x 3» позицией не является
        if (!preg_match('/\p{L}{3}/u', $name)) return '';
        // Слишком коротко, чтобы искать это в каталоге
        return mb_strlen($name) >= 4 ? $name : '';
    }
}
