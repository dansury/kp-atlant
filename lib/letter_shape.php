<?php
/**
 * Форма письма (модуль 040).
 *
 * Ответ клиенту у нас всегда одной формы, и держать её должна не модель, а
 * сервис: модель ошибается в мелочах — то поздоровается «Здравствуйте!», то
 * начнёт с «Спасибо за обращение», то вовсе с сути.
 *
 * Письмо начинается с обращения по ИМЕНИ И ОТЧЕСТВУ: «Никита Владимирович,
 * добрый день!». Отчества нет — по имени, имени нет — просто «Добрый день!».
 * Дальше идёт суть: что приложено (КП, счёт) или ответ на вопрос.
 */
final class LetterShape {

    /** Чем начинается любое наше письмо. */
    public static function greeting(?string $person): string {
        $name = self::address($person);
        return $name !== '' ? "$name, добрый день!" : 'Добрый день!';
    }

    /**
     * Имя и отчество из ФИО, как к человеку и обращаются.
     *
     * «Кузнецов Никита Владимирович» → «Никита Владимирович».
     * «Никита Кузнецов» → «Никита». Адрес, должность и название компании
     * обращением не становятся: лучше «Добрый день!», чем «info@, добрый день!».
     */
    public static function address(?string $person): string {
        $raw = trim((string)$person);
        if ($raw === '' || str_contains($raw, '@')) return '';
        $raw = trim((string)preg_replace('/\s+/u', ' ', $raw));

        $words = array_values(array_filter(explode(' ', $raw), fn($w) => $w !== ''));
        // Не ФИО: «Отдел закупок», «ООО Ромашка», «Снабжение»
        foreach ($words as $w) {
            if (!preg_match('/^\p{Lu}\p{L}+(-\p{Lu}?\p{L}+)?$/u', $w)) return '';
        }
        if (count($words) >= 3) return $words[1] . ' ' . $words[2];   // Фамилия Имя Отчество
        if (count($words) === 2) {
            // «Никита Владимирович» — уже обращение целиком
            if (self::isPatronymic($words[1])) return $words[0] . ' ' . $words[1];
            // «Никита Кузнецов» — имя первое, «Кузнецов Никита» — второе:
            // решает фамильный суффикс, а не порядок слов
            if (self::looksSurname($words[1])) return $words[0];
            return $words[1];
        }
        return count($words) === 1 ? $words[0] : '';
    }

    /** Фамилия на вид: «Кузнецов», «Ильина», «Ковальчук», «Достоевский». */
    private static function looksSurname(string $word): bool {
        return (bool)preg_match('/(ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|ский|ская|цкий|цкая|ко|ук|юк|швили|дзе|ян)$/ui', $word)
            && !self::isPatronymic($word);
    }

    private static function isPatronymic(string $word): bool {
        return (bool)preg_match('/(ович|евич|ьич|инич|овна|евна|ична|инична)$/ui', $word);
    }

    /**
     * Поставить письму нашу форму: обращение первой строкой, дальше текст.
     *
     * Приветствие, написанное моделью, заменяется нашим — двух приветствий в
     * письме не бывает. Всё остальное, что она написала, сохраняется как есть.
     */
    public static function apply(string $text, ?string $person): string {
        $text = trim(str_replace(["\r\n", "\r"], "\n", $text));
        $lines = explode("\n", $text);
        // Первая непустая строка — приветствие? Тогда она уходит: своё у нас есть
        foreach ($lines as $i => $line) {
            if (trim($line) === '') continue;
            if (self::isGreeting($line)) array_splice($lines, $i, 1);
            break;
        }
        $body = trim(implode("\n", $lines));
        return self::greeting($person) . ($body !== '' ? "\n\n" . $body : '');
    }

    /**
     * Строка-приветствие, своя или чужая: «Здравствуйте!», «Добрый день!» и
     * «Никита Владимирович, добрый день!» — всё это одно и то же место письма.
     * Своё приветствие узнаётся тоже: иначе повторная подстановка удвоила бы его.
     */
    private static function isGreeting(string $line): bool {
        $l = mb_strtolower(trim($line));
        return (bool)preg_match(
            '/^(.{0,40}?,\s*)?(добрый (день|вечер)|доброе утро|здравствуйте|приветствую|день добрый)/u', $l);
    }

    /**
     * Что письмо должно сказать после обращения — общая часть всех промптов
     * ответа. Лежит здесь, а не в каждом из пятнадцати промптов по отдельности:
     * форма письма одна, и меняться она должна в одном месте.
     */
    public static function instruction(): string {
        return <<<'TXT'

===== ФОРМА ПИСЬМА (обязательна) =====
Приветствие НЕ пиши — его подставит система строкой «Имя Отчество, добрый день!».
Начинай сразу с сути, первой же фразой:
- приложено КП → «Прикладываем файл КП по вашему запросу» и дальше пояснения:
  чего нет в наличии, какие сроки, что предложено аналогом и почему;
- приложен счёт → «Прикладываем счёт» и что дальше происходит после оплаты;
- вопрос без вложений → прямой ответ на заданный вопрос, без предисловий.
Не пиши подпись и не прощайся — подпись менеджера подставит система.
TXT;
    }
}
